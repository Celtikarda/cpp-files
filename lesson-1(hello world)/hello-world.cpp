#include <iostream>  // "cin" ve "cout" gibi ifadelerin çalışmasını sağlar. "#include" önişlemciye "<iostream>" kopyalamasını sağlar.
using namespace std; // her seferinde "std::cout" yazmak istemezsek bu kullanılır.

int main() { // Program ilk burda çalışır. Her programda olması gerekit.

    cout << "Hello world!"; // Ekrana bi şi yazdırmak istersek "cout" kullanılır. <iostream> olmazsa cout çalışmaz.
    // "//" yorum satırı oluşturmak için kullanılır.
    // ";" kod bitti demektir.
    return 0; // maini bitirir. Bunu yazarsak bundan sonraki hiçbir kod çalşmaz.
}